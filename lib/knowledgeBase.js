import policy from "../data/policy.json";
import faq from "../data/faq.json";

function formatDoc(doc) {
  const header = [
    `【文件名稱】${doc.title}`,
    `【版本】${doc.version}`,
    `【文件類型】${doc.document_type}`,
    `【生效/文件日期】${doc.effective_date}`,
    `【效力說明】${doc.authority}`,
    `【引用標籤】${doc.citation_label}`,
  ].join("\n");

  const body = doc.sections
    .map(
      (s) =>
        `--- ${s.article_no}｜${s.article_name} ---\n主題關鍵字：${s.topic.join("、")}\n內容：${s.content}`
    )
    .join("\n\n");

  return `${header}\n\n${body}`;
}

export function buildKnowledgeBaseText() {
  return [
    "======= 文件一（正式規章，效力最高） =======",
    formatDoc(policy),
    "",
    "======= 文件二（輔助說明，僅供參考） =======",
    formatDoc(faq),
  ].join("\n");
}

